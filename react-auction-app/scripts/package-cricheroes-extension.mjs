// Publishes the CricHeroes Chrome extension zip to Firebase Storage only when its sources change.
// The Storage URL is written to src/config/cricheroesExtension.ts, so builds and deploys reuse it.
// Usage: npm run package:cricheroes-extension [-- --force]
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import JSZip from 'jszip';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const extensionRoot = resolve(projectRoot, 'cricheroes-sync-extension');
const configPath = resolve(projectRoot, 'src/config/cricheroesExtension.ts');
const BUCKET = 'e-auction-store.firebasestorage.app';
const packageFiles = [
  'manifest.json',
  'background.js',
  'scorecard-parser.js',
  'content.js',
  'popup.html',
  'popup.css',
  'popup.js',
  'README.md',
  'icons/icon16.png',
  'icons/icon32.png',
  'icons/icon48.png',
  'icons/icon128.png',
];

const contents = await Promise.all(packageFiles.map(file => readFile(resolve(extensionRoot, file))));
const hash = createHash('sha256');
packageFiles.forEach((file, index) => hash.update(file).update('\0').update(contents[index]));
const sourceHash = hash.digest('hex').slice(0, 16);

const current = await readFile(configPath, 'utf8').catch(() => '');
const currentHash = current.match(/hash: '([0-9a-f]*)'/)?.[1];
const currentUrl = current.match(/url: '([^']*)'/)?.[1];
if (!process.argv.includes('--force') && currentHash === sourceHash && currentUrl) {
  console.info(`CricHeroes extension unchanged (${sourceHash}); reusing the published Storage zip.`);
  process.exit(0);
}

const zip = new JSZip();
const extensionFolder = zip.folder('cricheroes-live-sync');
packageFiles.forEach((file, index) => extensionFolder.file(file, contents[index]));
const body = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE', compressionOptions: { level: 8 } });

const objectName = `downloads/cricheroes-live-sync-${sourceHash}.zip`;
const response = await fetch(`https://firebasestorage.googleapis.com/v0/b/${BUCKET}/o?name=${encodeURIComponent(objectName)}`, {
  method: 'POST',
  headers: { 'Content-Type': 'application/zip' },
  body,
});
if (!response.ok) {
  console.error(`Uploading the extension to Firebase Storage failed: ${response.status} ${await response.text()}`);
  process.exit(1);
}
const { downloadTokens } = await response.json();
const url = `https://firebasestorage.googleapis.com/v0/b/${BUCKET}/o/${encodeURIComponent(objectName)}?alt=media&token=${downloadTokens}`;

await writeFile(configPath, `// Generated by scripts/package-cricheroes-extension.mjs — do not edit by hand.
export const CRICHEROES_EXTENSION = {
  hash: '${sourceHash}',
  url: '${url}',
} as const;
`);
console.info(`Published CricHeroes extension ${sourceHash} to Firebase Storage (${(body.length / 1024).toFixed(1)} KB).`);